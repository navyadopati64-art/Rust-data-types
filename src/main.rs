fn main() {
    // Integer
    let age: i32 = 25;
    let year: i64 = 2026;

    // Unsigned Integer
    let count: u32 = 10;

    // Floating-point
    let price: f64 = 99.99;
    let rating: f32 = 4.5;

    // Boolean
    let is_active: bool = true;
    let is_logged_in: bool = false;

    // Character
    let grade: char = 'A';
    let symbol: char = '#';

    println!("Age: {}", age);
    println!("Year: {}", year);
    println!("Count: {}", count);
    println!("Price: {}", price);
    println!("Rating: {}", rating);
    println!("Is Active: {}", is_active);
    println!("Is Logged In: {}", is_logged_in);
    println!("Grade: {}", grade);
    println!("Symbol: {}", symbol);
}
